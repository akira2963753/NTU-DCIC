function fh = new_fig(name, sz)
% Create a figure with the HW1 style (LaTeX text) applied to all its children
if nargin < 2, sz = [900 520]; end
p = hw_palette();

fh = figure('Name', name, 'Color', 'w', 'Position', [100 100 sz]);
set(fh, ...
    'DefaultTextInterpreter', 'latex', ...
    'DefaultAxesTickLabelInterpreter', 'latex', ...
    'DefaultLegendInterpreter', 'latex', ...
    'DefaultConstantLineInterpreter', 'latex', ...
    'DefaultAxesFontSize', 13, ...
    'DefaultAxesTitleFontSizeMultiplier', 1.1, ...
    'DefaultAxesLabelFontSizeMultiplier', 1.05, ...
    'DefaultAxesTitleFontWeight', 'normal', ...
    'DefaultAxesXColor', p.ink2, ...
    'DefaultAxesYColor', p.ink2, ...
    'DefaultAxesGridColor', p.grid, ...
    'DefaultAxesGridAlpha', 1, ...
    'DefaultAxesXGrid', 'on', ...
    'DefaultAxesYGrid', 'on', ...
    'DefaultAxesBox', 'off', ...
    'DefaultAxesTickDir', 'out', ...
    'DefaultAxesTickLength', [0.006 0.006], ...
    'DefaultAxesLineWidth', 0.8, ...
    'DefaultAxesLayer', 'bottom', ...
    'DefaultTextColor', p.ink, ...
    'DefaultLegendFontSize', 12, ...
    'DefaultLegendBox', 'off', ...
    'DefaultLineLineWidth', 1.6);
end
